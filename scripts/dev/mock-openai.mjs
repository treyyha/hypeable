#!/usr/bin/env node
/**
 * Tiny OpenAI-compatible streaming server for local pipeline proofs.
 *
 *   node scripts/dev/mock-openai.mjs
 *
 * Listens on 127.0.0.1:8787. Accepts any Bearer token. Does not log headers.
 */
import http from 'node:http';

const PORT = Number(process.env.MOCK_OPENAI_PORT || 8787);
const HOST = process.env.MOCK_OPENAI_HOST || '127.0.0.1';

export const MOCK_PLAN = {
  title: 'Notes app',
  summary: 'A small notes app with tags.',
  pages: [{ name: 'Home', purpose: 'List and open notes' }],
  data: [{ entity: 'Note', storage: 'localStorage' }],
  features: [
    { id: 'list', text: 'List notes' },
    { id: 'tags', text: 'Tag a note', optional: true },
  ],
  stack: ['Vite', 'React'],
  assumptions: ['Single browser user'],
  risks: ['localStorage quota'],
};

const MOCK_USAGE = { prompt_tokens: 2000, completion_tokens: 1000, total_tokens: 3000 };

const MOCK_ARTIFACT = `I'll create a small todo app.

<boltArtifact id="todo-app" title="Todo app">
<boltAction type="file" filePath="index.html"><!DOCTYPE html>
<html>
  <head><title>Todo</title></head>
  <body><h1>Todos</h1><ul id="list"></ul></body>
</html>
</boltAction>
<boltAction type="file" filePath="README.md"># Todo
A tiny todo app generated by the mock.
</boltAction>
<boltAction type="shell">echo ready</boltAction>
</boltArtifact>`;

function sendSseChat(res, chunks, usage = MOCK_USAGE) {
  res.writeHead(200, {
    'Content-Type': 'text/event-stream; charset=utf-8',
    'Cache-Control': 'no-store',
    Connection: 'keep-alive',
  });

  for (const content of chunks) {
    res.write(
      `data: ${JSON.stringify({
        id: 'chatcmpl-mock',
        object: 'chat.completion.chunk',
        created: 1,
        model: 'mock-model',
        choices: [{ index: 0, delta: { content }, finish_reason: null }],
      })}\n\n`,
    );
  }

  res.write(
    `data: ${JSON.stringify({
      id: 'chatcmpl-mock',
      object: 'chat.completion.chunk',
      created: 1,
      model: 'mock-model',
      choices: [{ index: 0, delta: {}, finish_reason: 'stop' }],
    })}\n\n`,
  );
  res.write(
    `data: ${JSON.stringify({
      id: 'chatcmpl-mock',
      object: 'chat.completion.chunk',
      created: 1,
      model: 'mock-model',
      choices: [],
      usage,
    })}\n\n`,
  );
  res.write('data: [DONE]\n\n');
  res.end();
}

function readBody(req) {
  return new Promise((resolve) => {
    const chunks = [];
    let settled = false;
    const finish = () => {
      if (settled) {
        return;
      }

      settled = true;
      resolve(Buffer.concat(chunks).toString('utf8'));
    };

    const expected = Number(req.headers['content-length'] || 0);
    let received = 0;

    req.on('data', (chunk) => {
      chunks.push(chunk);
      received += chunk.length;

      if (expected > 0 && received >= expected) {
        finish();
      }
    });
    req.on('end', finish);
    req.on('error', finish);
    setTimeout(finish, 2000);
  });
}

function isPlanningRequest(body) {
  return body.includes('hypeable-plan') && body.includes('Do NOT output any boltArtifact');
}

export function createMockOpenAIServer() {
  return http.createServer((req, res) => {
    const url = req.url || '/';

    if (req.method === 'GET' && (url === '/v1/models' || url === '/models')) {
      res.writeHead(200, { 'Content-Type': 'application/json', 'Cache-Control': 'no-store' });
      res.end(JSON.stringify({ data: [{ id: 'mock-model' }] }));
      return;
    }

    if (req.method === 'POST' && (url === '/v1/chat/completions' || url === '/chat/completions')) {
      void readBody(req).then((body) => {
        if (isPlanningRequest(body)) {
          const fence = `Here is a short plan.\n\n\`\`\`hypeable-plan\n${JSON.stringify(MOCK_PLAN, null, 2)}\n\`\`\``;
          sendSseChat(res, [fence]);
          return;
        }

        sendSseChat(res, [MOCK_ARTIFACT]);
      });
      return;
    }

    res.writeHead(404, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ error: { message: 'not found', type: 'invalid_request_error' } }));
  });
}

if (import.meta.url === `file://${process.argv[1].replaceAll('\\', '/')}` || process.argv[1]?.endsWith('mock-openai.mjs')) {
  const server = createMockOpenAIServer();
  server.listen(PORT, HOST, () => {
    console.log(`mock openai listening on http://${HOST}:${PORT}`);
  });
}
